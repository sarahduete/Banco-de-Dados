
CREATE TABLE CATEGORIAS (
	COD_CATEGORIA INTEGER PRIMARY KEY AUTOINCREMENT,
	NOME_CATEGORIA TEXT NOT NULL
);

CREATE TABLE CLIENTES (
	COD_CLIENTE INTEGER PRIMARY KEY AUTOINCREMENT,
	RG TEXT,
	NOME TEXT,
	ENDERECO TEXT,
	BAIRRO TEXT,
	CIDADE TEXT,
	ESTADO TEXT,
	TELEFONE TEXT,
	EMAIL TEXT,
	DATANASCIMENTO datetime,
	SEXO TEXT
);

CREATE TABLE FILMES (
	COD_FILME INTEGER PRIMARY KEY AUTOINCREMENT,
	FILME TEXT NOT NULL,
	COD_CATEGORIA INTEGER NOT NULL,
	DIRETOR TEXT,
	VALOR_LOCACAO REAL,
	RESERVADO TEXT DEFAULT 'n',
	FOREIGN KEY (COD_CATEGORIA) REFERENCES CATEGORIA(COD_CATEGORIA)
);

CREATE TABLE LOCACOES(
	COD_LOCACAO INTEGER PRIMARY KEY AUTOINCREMENT,
	COD_CLIENTE INTEGER,
	COD_FILME INTEGER,
	DATA_RETIRADA datetime,
	DATA_DEVOLUCAO datetime,
	FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTES(COD_CLIENTE),
	FOREIGN KEY (COD_FILME) REFERENCES FILMES(COD_FILME)
);

ALTER TABLE CATEGORIA 
RENAME TO CATEGORIAS
